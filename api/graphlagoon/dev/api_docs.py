"""Generated API references for the docs site, from the running code.

- ``docs/guide/agents-mcp-tools.md``: every MCP tool (description, parameters,
  the human route it mirrors), the resources and the prompts, read from
  ``mcp/server.build_server()``: what Claude Code and other agents see.
- ``docs/public/openapi.json``: the REST spec of ``create_app`` (the one Swagger
  serves at ``{prefix}/docs`` when ``api_docs_enabled``), for systems that
  integrate over REST and for client generators.

``python -m graphlagoon.dev.api_docs`` writes both; ``--check`` exits 1 when
the committed files differ (``make docs-api`` / ``make docs-build``;
``tests/test_api_docs.py`` runs the same check).
"""

from __future__ import annotations

import argparse
import asyncio
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MCP_PAGE = ROOT / "docs/guide/agents-mcp-tools.md"
OPENAPI_FILE = ROOT / "docs/public/openapi.json"

# The groups of docs/guide/agents-mcp.md; a tool in none of them fails the check.
GROUPS: list[tuple[str, list[str]]] = [
    ("Cases", ["list_cases", "get_case", "create_case", "update_case"]),
    ("Brief and material", ["get_brief", "write_brief", "list_items", "read_item", "update_item", "search_case"]),
    ("Adding material", ["add_note", "add_document", "add_table", "save_query", "import_file", "create_exploration", "add_item"]),
    ("Queries and tables", ["run_query", "join_tables", "compare_tables", "promote_tables"]),
    ("Annotations and evidence", ["annotate", "group", "list_annotations", "pin_evidence"]),
    ("Tasks", ["list_tasks", "add_task", "update_task"]),
    ("Graph and entities", ["get_graph", "search_entities", "get_entity", "lookup_enrichment", "find_entity_cases"]),
    ("Analyses", ["run_analysis"]),
    ("Reports and decisions", ["render_report", "propose_decision"]),
    ("Journal", ["list_events", "changes_since"]),
    ("Organization", ["get_case_type", "get_playbook"]),
]


def _escape(text: str) -> str:
    """Markdown text that VitePress renders as written: ``<`` / ``>`` outside code
    spans would be parsed as HTML (``fields.<id>``); the page is ``v-pre`` so
    ``{{…}}`` stays literal."""
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(p if p.startswith("`") else p.replace("<", "&lt;").replace(">", "&gt;") for p in parts)


def _type(schema: dict) -> str:
    if "anyOf" in schema:
        kinds = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " or ".join(kinds) if kinds else "null"
    kind = schema.get("type", "any")
    if kind == "array":
        return f"list of {_type(schema.get('items', {}))}"
    if kind == "object":
        return "object"
    if schema.get("format") == "uuid":
        return "uuid"
    return kind


def _default(schema: dict) -> str:
    if "default" not in schema:
        return ""
    return "null" if schema["default"] is None else f"`{json.dumps(schema['default'])}`"


def _description(text: str) -> str:
    """A docstring as markdown paragraphs: re-flow the lines, keep blank lines and list items."""
    lines = [line.strip() for line in (text or "").strip().splitlines()]
    out, para = [], []
    for line in lines:
        if not line or line.startswith("- "):
            if para:
                out.append(" ".join(para))
                para = []
            if line:
                out.append(line)
            continue
        para.append(line)
    if para:
        out.append(" ".join(para))
    return _escape("\n\n".join(out))


async def _mcp_markdown() -> str:
    from graphlagoon.mcp.server import build_server
    from graphlagoon.services import org_library

    server = build_server()
    tools = {t.name: t for t in await server.list_tools()}
    grouped = [name for _, names in GROUPS for name in names]
    missing = sorted(set(tools) - set(grouped))
    if missing:
        raise SystemExit(f"api_docs.GROUPS does not list these MCP tools: {missing}")
    templates = await server.list_resource_templates()

    out = [
        "---",
        "outline: [2, 3]",
        "---",
        "",
        "<!-- Generated by `python -m graphlagoon.dev.api_docs` (make docs-api) from the MCP server. Do not edit. -->",
        "",
        "# MCP tool reference",
        "",
        "::: v-pre",
        "",
        f"Every tool of the MCP server at `{{prefix}}/mcp`, as an agent sees it in `tools/list` ({len(tools)} tools). "
        "How to connect, what arrives suggested and what agents never do: [AI Agents (MCP)](./agents-mcp.md). "
        "Each tool mirrors a REST route a person uses (*human twin*); case data comes back wrapped in "
        "`untrusted_data`.",
        "",
        "| Group | Tools |",
        "|---|---|",
    ]
    for group, names in GROUPS:
        links = ", ".join(f"[`{n}`](#{n.replace('_', '-')})" for n in names)
        out.append(f"| {group} | {links} |")
    for group, names in GROUPS:
        out += ["", f"## {group}"]
        for name in names:
            tool = tools[name]
            twins = (tool.meta or {}).get("human_equivalent") or []
            out += ["", f"### {name}", "", _description(tool.description)]
            if twins:
                out += ["", "Human twin: " + ", ".join(f"`{t}`" for t in twins)]
            props = tool.input_schema.get("properties", {})
            required = set(tool.input_schema.get("required", []))
            if props:
                out += ["", "| Parameter | Type | Required | Default |", "|---|---|---|---|"]
                for pname, pschema in props.items():
                    out.append(
                        f"| `{pname}` | {_type(pschema).replace('|', '/')} | {'yes' if pname in required else ''} | {_default(pschema)} |"
                    )
    out += ["", "## Resources", "", "| URI template | Content |", "|---|---|"]
    for t in templates:
        out.append(f"| `{t.uri_template}` | {_escape(' '.join((t.description or '').split()))} |")
    playbooks = ", ".join(f"`{slug}`" for slug in org_library.SEED)
    out += [
        "",
        "## Prompts",
        "",
        "One prompt per playbook of the org library (built in: "
        f"{playbooks}; the org's own appear too), with `investigation_id` as argument, plus `playbook(slug, "
        "investigation_id)` for any library doc. Claude Code shows them as slash commands "
        "(`/mcp__graphlagoon__triage <case id>`).",
        "",
        ":::",
        "",
    ]
    return "\n".join(out)


def mcp_markdown() -> str:
    return asyncio.run(_mcp_markdown())


def openapi_json() -> str:
    from graphlagoon.app import create_app
    from graphlagoon.config import Settings

    app = create_app(settings=Settings(dev_mode=True, api_docs_enabled=True), include_frontend=False)
    return json.dumps(app.openapi(), indent=2, ensure_ascii=False) + "\n"


def _outputs() -> dict[Path, str]:
    return {MCP_PAGE: mcp_markdown(), OPENAPI_FILE: openapi_json()}


def stale() -> list[Path]:
    """The committed references that differ from what the code generates."""
    return [path for path, text in _outputs().items() if not path.exists() or path.read_text() != text]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed reference is stale")
    args = parser.parse_args(argv)
    if args.check:
        bad = stale()
        for p in bad:
            print(f"stale: {p.relative_to(ROOT)} (run `make docs-api`)", file=sys.stderr)
        return 1 if bad else 0
    for path, text in _outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
